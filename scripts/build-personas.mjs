// personas/*.md と personas/personas.json から src/generated/personas.ts を生成する
// Generates src/generated/personas.ts from personas/*.md and personas/personas.json
//
// Vercel の関数にはmdファイルが同梱される保証がないため、ビルド時にTSへ埋め込む
// Markdown files are not guaranteed to ship with a Vercel function, so they are inlined at build time
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src/generated/personas.ts");
const checkOnly = process.argv.includes("--check");

const manifest = JSON.parse(readFileSync(join(root, "personas/personas.json"), "utf8"));
if (!Array.isArray(manifest) || manifest.length === 0) {
  throw new Error("personas/personas.json must be a non-empty array");
}

const seen = new Set();
const personas = manifest.map((entry) => {
  for (const key of ["id", "name", "description", "file"]) {
    if (typeof entry[key] !== "string" || entry[key].trim() === "") {
      throw new Error(`personas.json: "${key}" is required (entry: ${JSON.stringify(entry)})`);
    }
  }
  if (!/^[a-z0-9][a-z0-9-]*$/.test(entry.id)) {
    throw new Error(`personas.json: id must match [a-z0-9-]+ (got "${entry.id}")`);
  }
  if (seen.has(entry.id)) throw new Error(`personas.json: duplicate id "${entry.id}"`);
  seen.add(entry.id);

  const raw = readFileSync(join(root, "personas", entry.file), "utf8").replace(/\r\n/g, "\n");
  // 最初の「---」の行より下を、システムプロンプトとして使う / Everything below the first "---" line is the system prompt
  const separator = raw.indexOf("\n---\n");
  if (separator === -1) throw new Error(`${entry.file}: no "---" separator line found`);
  const systemPrompt = raw.slice(separator + "\n---\n".length).trim();
  if (systemPrompt === "") throw new Error(`${entry.file}: system prompt is empty`);

  return {
    id: entry.id,
    name: entry.name.trim(),
    description: entry.description.trim(),
    systemPrompt,
  };
});

const body = `// このファイルは scripts/build-personas.mjs が生成する。直接編集しない / Generated by scripts/build-personas.mjs. Do not edit by hand.
// 人物設定を直すときは personas/*.md を編集して \`pnpm personas\` を実行する / Edit personas/*.md and run \`pnpm personas\`.

export interface PersonaDefinition {
  readonly id: string;
  readonly name: string;
  readonly description: string;
  readonly systemPrompt: string;
}

export const PERSONAS: readonly PersonaDefinition[] = ${JSON.stringify(personas, null, 2)};
`;

if (checkOnly) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    // 無ければ不一致として扱う / Treat a missing file as out of date
  }
  if (current !== body) {
    console.error("src/generated/personas.ts is out of date. Run `pnpm personas`.");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, body);
  console.log(`generated ${personas.length} personas -> src/generated/personas.ts`);
}
