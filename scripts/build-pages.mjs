// pages/*.html から src/generated/pages.ts を生成する
// Generates src/generated/pages.ts from pages/*.html
//
// 画面は関数のルートから返す。Vercel が public/ を配信するかどうかに頼らず、ローカルと同じ経路で動かすため、ビルド時にTSへ埋め込む
// The screens are served from a route, so they work regardless of whether Vercel serves public/, and locally through the same path.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src/generated/pages.ts");
const checkOnly = process.argv.includes("--check");

const pages = { INDEX_HTML: "pages/index.html", ADMIN_HTML: "pages/admin.html" };

const body =
  `// このファイルは scripts/build-pages.mjs が生成する。直接編集しない / Generated by scripts/build-pages.mjs. Do not edit by hand.\n` +
  `// 画面を直すときは pages/*.html を編集して \`pnpm pages\` を実行する / Edit pages/*.html and run \`pnpm pages\`.\n\n` +
  Object.entries(pages)
    .map(([name, file]) => `export const ${name} = ${JSON.stringify(readFileSync(join(root, file), "utf8"))};\n`)
    .join("\n");

if (checkOnly) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    // 無ければ不一致として扱う / Treat a missing file as out of date
  }
  if (current !== body) {
    console.error("src/generated/pages.ts is out of date. Run `pnpm pages`.");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, body);
  console.log(`generated ${Object.keys(pages).length} pages -> src/generated/pages.ts`);
}
